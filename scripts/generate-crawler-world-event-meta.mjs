#!/usr/bin/env node
/**
 * Slim world-event rows for Edge middleware crawler meta.
 *
 *   npm run generate:crawler-world-event-meta
 *
 * Input:  src/pages/Home/data/worldEvents.json
 *         src/pages/Home/data/travelSpots-list.json (place labels only)
 * Output: src/edge/worldEventCrawlerSources.generated.js
 *
 * The edge bundle must not import worldEvents.js. That module uses JSON import
 * attributes, which the Vercel edge bundler rejects.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const eventsFile = join(root, 'src/pages/Home/data/worldEvents.json');
const spotsFile = join(root, 'src/pages/Home/data/travelSpots-list.json');
const outFile = join(root, 'src/edge/worldEventCrawlerSources.generated.js');

function text(value) {
  const trimmed = String(value ?? '').trim();
  return trimmed || undefined;
}

function heroUrl(event) {
  const direct = text(event?.heroImage);
  if (direct) return direct;
  const first = Array.isArray(event?.heroImages) ? event.heroImages[0]?.url : '';
  return text(first);
}

function slimEvent(event) {
  const id = text(event?.id);
  const slug = text(event?.slug)?.toLowerCase();
  if (!id || !slug) {
    throw new Error('[crawler-world-event-meta] event is missing id or slug');
  }
  const row = { id, slug };
  const title = text(event.title);
  const titleEn = text(event.titleEn);
  const startDate = text(event.startDate);
  const endDate = text(event.endDate);
  const detailOverview = text(event.detailOverview);
  const detailOverviewEn = text(event.detailOverviewEn);
  const heroImage = heroUrl(event);
  if (title) row.title = title;
  if (titleEn) row.titleEn = titleEn;
  if (startDate) row.startDate = startDate;
  if (endDate) row.endDate = endDate;
  if (detailOverview) row.detailOverview = detailOverview;
  if (detailOverviewEn) row.detailOverviewEn = detailOverviewEn;
  if (heroImage) row.heroImage = heroImage;
  return row;
}

export function writeWorldEventCrawlerSources() {
  const events = JSON.parse(readFileSync(eventsFile, 'utf8')).events;
  const spots = JSON.parse(readFileSync(spotsFile, 'utf8'));
  if (!Array.isArray(events) || events.length === 0) {
    throw new Error('[crawler-world-event-meta] worldEvents.json has no events');
  }
  if (!Array.isArray(spots)) {
    throw new Error('[crawler-world-event-meta] travelSpots-list.json must be an array');
  }

  const spotBySlug = new Map();
  for (const spot of spots) {
    const slug = text(spot?.slug)?.toLowerCase();
    if (!slug || spotBySlug.has(slug)) continue;
    spotBySlug.set(slug, spot);
  }

  /** @type {Record<string, object>} */
  const slimEvents = {};
  /** @type {Record<string, { name: string, name_en: string }>} */
  const places = {};

  for (const event of events) {
    const row = slimEvent(event);
    if (slimEvents[row.id]) {
      throw new Error(`[crawler-world-event-meta] duplicate id: ${row.id}`);
    }
    const spot = spotBySlug.get(row.slug);
    if (!spot) {
      throw new Error(`[crawler-world-event-meta] no travel spot for slug ${row.slug} (${row.id})`);
    }
    slimEvents[row.id] = row;
    if (!places[row.slug]) {
      places[row.slug] = {
        name: text(spot.name) || '',
        name_en: text(spot.name_en) || '',
      };
    }
  }

  const orderedEvents = Object.fromEntries(
    Object.keys(slimEvents)
      .sort()
      .map((id) => [id, slimEvents[id]]),
  );
  const orderedPlaces = Object.fromEntries(
    Object.keys(places)
      .sort()
      .map((slug) => [slug, places[slug]]),
  );

  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(
    outFile,
    `// Generated by scripts/generate-crawler-world-event-meta.mjs — do not edit.\nexport default ${JSON.stringify({ events: orderedEvents, places: orderedPlaces }, null, 2)};\n`,
  );

  console.log('generate:crawler-world-event-meta');
  console.log(`  events        ${Object.keys(orderedEvents).length}`);
  console.log(`  place labels  ${Object.keys(orderedPlaces).length}`);
  console.log(`  output        ${outFile}`);
  return { events: Object.keys(orderedEvents).length, places: Object.keys(orderedPlaces).length, outFile };
}

const isDirect =
  Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isDirect) {
  writeWorldEventCrawlerSources();
}
