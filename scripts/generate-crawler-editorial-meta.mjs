#!/usr/bin/env node
/**
 * Editorial LogBook /blog/e/* crawler meta for Edge middleware.
 *
 *   npm run generate:crawler-editorial-meta
 *
 * Input:  src/data/logbookEditorialPublished.json (npm run sync:logbook-editorial-published)
 * Output: src/edge/crawlerEditorialMeta.generated.js
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { TRAVEL_SPOTS } from '../src/pages/Home/data/travelSpots.js';
import { buildEditorialCrawlerMetaBundle } from '../src/edge/editorialCrawlerMetaFromRow.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const listFile = join(root, 'src/data/logbookEditorialPublished.json');
const outFile = join(root, 'src/edge/crawlerEditorialMeta.generated.js');

const spotsBySlug = Object.fromEntries(TRAVEL_SPOTS.filter((s) => s?.slug).map((s) => [s.slug, s]));

const published = JSON.parse(readFileSync(listFile, 'utf8'));
/** @type {Record<string, Record<string, object>>} */
const meta = {};

for (const row of published) {
  const slug = String(row.slug || '').trim();
  if (!slug) continue;
  meta[slug] = buildEditorialCrawlerMetaBundle(row, { spotsBySlug });
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/generate-crawler-editorial-meta.mjs — do not edit.\nexport default ${JSON.stringify(meta, null, 2)};\n`,
);

console.log('generate:crawler-editorial-meta');
console.log(`  editorial slugs ${Object.keys(meta).length}`);
console.log(`  output        ${outFile}`);
