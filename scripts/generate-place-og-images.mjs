function hashSlug(slug) {
  let hash = 0;
  const value = String(slug || '');
  for (let i = 0; i < value.length; i += 1) {
    hash = (hash * 31 + value.charCodeAt(i)) >>> 0;
  }
  return hash;
}

function pickPoolImage(slug) {
  return OG_PHOTO_POOL[hashSlug(slug) % OG_PHOTO_POOL.length];
}

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const outFile = join(root, 'src/data/placeSeoOgImageOverrides.js');

const tier1Spots = TRAVEL_SPOTS.filter((spot) => spot.tier === 1).sort((a, b) =>
  String(a.slug).localeCompare(String(b.slug)),
);

/** @type {Record<string, string>} */
const overrides = {};

for (const spot of tier1Spots) {
  overrides[spot.slug] = pickPoolImage(spot.slug);
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/generate-place-og-images.mjs — do not edit.\nexport const PLACE_SEO_OG_IMAGE_OVERRIDES = ${JSON.stringify(overrides, null, 2)};\n`,
);

console.log('generate:place-og-images');
console.log(`  tier1 slugs ${tier1Spots.length}`);
console.log(`  output      ${outFile}`);
