## 둘째 날, 시미란으로 가는 배

### 당일치기 섬

**시미란 국립공원(Mu Ko Similan National Park)**의 2026–27 시즌은 2026년 10월 15일부터 2027년 5월 15일까지예요. 섬에서는 묵을 수 없고, 아침에 나가 저녁에 돌아오는 당일 일정만 돼요. 배는 대부분 타이므앙군의 **탑라무 선착장(Thap Lamu Pier)**과 그 근처에서 떠나는 스피드보트나 카타마란이고, 약 1시간 30분이 걸려요. 태국 정부홍보국은 당일 투어 상품을 이용하라고 권해요.

[사진 5]

외국인 입장료는 성인 500바트, 어린이 250바트예요. 식당과 매점, 화장실은 4번 섬과 8번 섬에만 있어요. 섬에는 ATM이 없고 전화 신호가 끊길 때가 있어 현금을 챙겨 가요. 산호에 해로운 성분이 없는 선크림을 쓰고 일회용 플라스틱은 줄여요. 따차이섬은 2016년부터 상륙이 막혀 있어요. [GATEO 시미란 제도 페이지](https://www.gateo.kr/place/similan-islands)에서 MOONi에게 여행 날짜를 알려 주고, 시미란 배를 사흘 가운데 어느 날에 넣을지 골라 보세요.

