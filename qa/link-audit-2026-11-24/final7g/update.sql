## 난바에 닿기 전에

### 공항에서 난바까지

간사이공항역(Kansai-Airport)에서 난카이 난바역(Namba)까지는 난카이 전철의 공항 특급 라피트(Rapi:t)가 가장 빠르다. 최단 34분이 걸리고, 승차권과 특급권을 묶은 디지털 티켓은 레귤러 시트 1,410엔, 슈퍼 시트 1,590엔이다. 특급권을 차 안에서 사면 300엔이 더 붙는다. 특급권 없이 타는 공항 급행은 약 45분이 걸린다.

**여행 팁 · 난카이 라피트(Rapi:t)**
