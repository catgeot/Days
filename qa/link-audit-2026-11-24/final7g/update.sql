### 장이 서는 요일

저녁에는 카오락 한가운데 방니앙의 **방니앙 시장(Bang Niang Market)**으로 가요. 월·수·목·토요일 14:00~22:00에 열리고, 상인이 300곳이 넘어요. 길거리 음식 구역에는 꼬치와 스프링롤, 해산물이, 농산물 구역에는 태국 과일과 채소가 놓여요. 시장 운영 측은 이른 저녁이 가장 활기찬 시간이라고 해요.

