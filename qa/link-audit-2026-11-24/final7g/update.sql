탑라무 선착장과 같은 타이므앙군의 람깬에는 미쉐린 가이드 빕구르망의 **끄라창 카오락(Krachang Khao Lak)**이 있어요. 대부분 살아 있는 해산물을 단품으로 조리하고, 그날의 추천은 스페셜 보드에 적어요. 멜린조 잎을 넣은 새우 코코넛 수프와 강황에 재운 자이언트 트레발리 구이가 대표 접시예요.

