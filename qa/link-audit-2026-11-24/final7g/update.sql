**여행 팁 · 시미란 국립공원(Mu Ko Similan National Park)**
- 시즌: 2026-10-15~2027-05-15 · 당일 일정만 · 모든 섬 숙박 금지
- 배: 대부분 탑라무 선착장(타이므앙군)과 근처에서 출발 · 스피드보트·카타마란 약 1시간 30분 · 당일 투어 상품 권장
