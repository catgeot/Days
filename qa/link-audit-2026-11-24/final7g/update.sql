## 첫째 날, 해변의 결

### 낭통에서 방삭까지

카오락의 해변은 성격이 갈려요. **낭통 해변(Nang Thong Beach)**은 쇼핑·식당·나이트라이프가 몰린 중심가에 있어 걸어서 다니기 편해요. **방삭 해변(Bang Sak Beach)**과 **팍윕 해변(Pak Weep Beach)**은 북적임에서 비켜 앉아 책을 읽거나 수영하고, 해변을 걷다 해 지는 바다를 보기 좋은 곳이에요.

