## 셋째 날, 북쪽 해안의 기억

### 이름이 새겨진 길

카오락에서 차로 약 40분, 반남켐 해안 가까이에 **반남켐 쓰나미 추모공원(Ban Nam Khem Tsunami Memorial Park)**이 있어요. 파도를 본뜬 굽은 콘크리트 벽이 쓰나미에 부서진 옛 어선과 마주 서 있고, 공원 다른 쪽 흙벽을 따라 이곳에서 희생된 1,400명이 넘는 이름이 새겨진 길이 이어져요. 공원 주변에는 해산물 식당과 관광안내소, 주민들이 만든 기념품 가게가 있고, 해변을 따라 어촌 마을까지 걸을 수 있어요.

**여행 팁 · 반남켐 쓰나미 추모공원(Ban Nam Khem Tsunami Memorial Park)**
- 위치: Bang Muang, Takua Pa, Phang Nga · 카오락에서 차로 약 40분
- 시간: 추모공원·해변 08:00~20:00 · 박물관 수~일 08:30~16:30
- 하이라이트: 파도 모양의 벽과 옛 어선 · 희생자 이름이 새겨진 길 · 해변의 어촌 마을
- 링크: [태국관광청 안내](https://thailand.prd.go.th/en/) · [지도에서 보기](https://www.google.com/maps/search/?api=1&query=Ban%20Nam%20Khem%20Tsunami%20Memorial%20Park%2C%20Bang%20Muang%2C%20Takua%20Pa%2C%20Phang%20Nga)

### 주석의 옛 도시

추모공원에서 약 7km 떨어진 따꾸아빠에는 **따꾸아빠 올드타운(Takua Pa Old Town)**이 있어요. 주석과 광물의 채굴·무역으로 외국 상인이 모이던 도시라 시노-포르투갈풍 건물이 늘어서 있고, 지금은 그 건물들이 카페와 잡화점으로 쓰여요. 벽에는 거리 그림이 많아 사진을 남기는 자리가 돼요.

**여행 팁 · 따꾸아빠 올드타운(Takua Pa Old Town)**
- 위치: Takua Pa, Phang Nga · 반남켐 추모공원에서 약 7km
- 하이라이트: 시노-포르투갈풍 건물을 고친 카페·잡화점 · 거리 벽화
- 링크: [태국관광청 안내](https://www.thailandgoodtravel.info/?locale=en) · [지도에서 보기](https://www.google.com/maps/search/?api=1&query=Takua%20Pa%20Old%20Town%2C%20Takua%20Pa%2C%20Phang%20Nga)

