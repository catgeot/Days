### 숲 쪽으로 한 걸음

해변에서 등을 돌리면 카오락-람루 국립공원이 있어요. 카오락에서 약 9km 떨어진 **똔총파 폭포(Ton Chong Fa Waterfall)**는 다섯 단으로 바위를 타고 내려와 큰 웅덩이에 고여요. 입구에서 폭포까지는 비교적 쉬운 길이고, 폭포 오른쪽으로 윗단에 오르는 길은 좁고 가파르며 미끄러워요.

